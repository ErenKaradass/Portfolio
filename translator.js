const getLanguage = () => localStorage.getItem("portfolioLanguage") || "en";

function setLanguage(language) {
  const normalizedLanguage = translations[language] ? language : "en";
  const elements = document.querySelectorAll("[data-i18n]");

  elements.forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[normalizedLanguage][key]) {
      element.textContent = translations[normalizedLanguage][key];
    }
  });

  // Fallback: translate plain text nodes that are not marked with data-i18n
  translateUnmarked(normalizedLanguage);

  const buttons = document.querySelectorAll("[data-lang-toggle]");
  buttons.forEach((button) => {
    const isActive = button.dataset.langToggle === normalizedLanguage;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem("portfolioLanguage", normalizedLanguage);
  document.documentElement.lang = normalizedLanguage === "de" ? "de" : "en";
}

document.addEventListener("DOMContentLoaded", () => {
  const initialLanguage = getLanguage();
  const buttons = document.querySelectorAll("[data-lang-toggle]");

  buttons.forEach((button) => {
    button.addEventListener("click", () => setLanguage(button.dataset.langToggle));
  });

  setLanguage(initialLanguage);
});

// --- Fallback literal translations for untagged text nodes ---
// Build a lookup keyed by normalized text (both EN and DE) to {en, de}
const literalLookup = {};

function buildLiteralLookup() {
  Object.keys(translations.en).forEach((key) => {
    const eng = translations.en[key];
    const ger = translations.de[key];
    if (typeof eng === 'string' && eng.trim().length > 0) {
      const engN = eng.replace(/\s+/g, ' ').trim();
      const gerN = (ger || eng).replace(/\s+/g, ' ').trim();
      literalLookup[engN] = { en: eng, de: ger || eng };
      literalLookup[gerN] = { en: eng, de: ger || eng };
    }
  });
}

function translateUnmarked(language) {
  if (!Object.keys(literalLookup).length) buildLiteralLookup();

  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, null, false);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);

  nodes.forEach((textNode) => {
    const parent = textNode.parentElement;
    if (!parent) return;
    const tag = parent.tagName.toLowerCase();
    if (tag === 'script' || tag === 'style' || tag === 'iframe' || tag === 'code' || tag === 'pre') return;
    if (tag === 'a' && parent.href && (parent.href.startsWith('mailto:') || parent.href.startsWith('tel:'))) return;

    const original = textNode.textContent.replace(/\s+/g, ' ').trim();
    if (!original) return;

    const entry = literalLookup[original];
    if (entry && entry[language]) {
      textNode.textContent = entry[language];
    }
  });
}
